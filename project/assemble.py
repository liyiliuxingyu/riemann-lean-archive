#!/usr/bin/env python3
"""Assemble the human-readable mathematical reconstruction into one TeX file."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CHAPTERS = [
    'preamble.tex', 'overview.tex', 'bridge.tex', 'arithmetic.tex',
    'window_proof.tex', 'finish.tex', 'appendix.tex',
]
parts = ['% Standalone XeLaTeX source. Generated by assemble.py.\n']
for name in CHAPTERS:
    parts.append(f'\n% ===== {name} =====\n')
    body = (ROOT / 'chapters' / name).read_text(encoding='utf-8')
    if name == 'appendix.tex':
        extra = (ROOT / 'chapters' / 'source_delivery.tex').read_text(encoding='utf-8')
        body = body.replace('\\backmatter', extra + '\n\\backmatter')
    parts.append(body)
path = ROOT / '黎曼猜想_人类可读证明主线.tex'
path.write_text('\n'.join(parts), encoding='utf-8')
print(path)
